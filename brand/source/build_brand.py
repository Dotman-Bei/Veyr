"""Build the Veyr logo system from one geometry source.

Usage (repo root, needs `pip install fonttools brotli` and `npm install`):
    python3 brand/source/build_brand.py


Mark: a heavy geometric V with a flat-cut vertex, seated on a verdict block of
the vertex's width. The logotype uses the mark as the "V" of "veyr", so the
block sits below the baseline like the y's descender.
"""
import json, os, subprocess, sys
HERE=os.path.dirname(os.path.abspath(__file__))
ROOT=os.path.dirname(os.path.dirname(HERE))          # repo root
OUT=os.path.join(ROOT, 'brand'); os.makedirs(OUT, exist_ok=True)
INK='#1E174F'; EMBER='#B83A14'; EMBER_BRIGHT='#E2622B'; CREAM='#F7F1E9'; BLACK='#000000'; WHITE='#FFFFFF'

# ---- mark geometry: 42 x 42 box. V is 30 tall (== logotype x-height) ----
W=42; BAR=11.5; FLAT=10.5; VH=30
bl=(W-FLAT)/2; notch=VH*((W/2-BAR)/bl)
f=lambda n: f'{n:.3f}'.rstrip('0').rstrip('.')
V=f'M0 0H{f(BAR)}L{f(W/2)} {f(notch)}L{f(W-BAR)} 0H{W}L{f(bl+FLAT)} {VH}H{f(bl)}Z'
BLOCK=dict(x=bl, y=34, w=FLAT, h=8, rx=1.5)
MARK_W, MARK_H = W, 42
def block(fill): return f'<rect x="{f(BLOCK["x"])}" y="{BLOCK["y"]}" width="{f(BLOCK["w"])}" height="{BLOCK["h"]}" rx="{BLOCK["rx"]}" fill="{fill}"/>'
def mark_body(v, b): return f'<path d="{V}" fill="{v}"/>' + block(b)

# ---- logotype: mark + "eyr" in Outfit Bold outlines (SIL OFL 1.1) ----
g=json.loads(subprocess.check_output([sys.executable, os.path.join(HERE,'glyphs.py'),'700','eyr','-12']))
SCALE=VH/g['xHeight']; xmin,ymin,xmax,ymax=g['bounds']
GAP=2.5
TEXT_X=MARK_W+GAP
LOGO_W=round(TEXT_X+(xmax-xmin)*SCALE, 3)
TOP=round(min(0, VH-ymax*SCALE), 3); BOTTOM=round(max(MARK_H, VH-ymin*SCALE), 3)
TEXT_T=f'translate({f(TEXT_X-xmin*SCALE)} {VH}) scale({SCALE:.6f})'
def text(fill): return f'<path transform="{TEXT_T}" d="{g["d"]}" fill="{fill}"/>'

def svg(w, h, body, y=0):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 {y:g} {w:g} {h:g}" role="img" aria-label="Veyr">'
            f'<title>Veyr</title>{body}</svg>\n')
def write(name, content):
    open(os.path.join(OUT, name), 'w').write(content); print('wrote brand/'+name)

for suffix, v, b, t in [('', INK, EMBER, INK), ('-on-dark', CREAM, EMBER_BRIGHT, CREAM),
                        ('-mono-black', BLACK, BLACK, BLACK), ('-mono-white', WHITE, WHITE, WHITE)]:
    write(f'veyr-logo{suffix}.svg', svg(LOGO_W, round(BOTTOM-TOP,3), mark_body(v, b) + text(t), TOP))
    write(f'veyr-mark{suffix}.svg', svg(MARK_W, MARK_H, mark_body(v, b)))

ICON_T=f'translate({f((64-MARK_W)/2)} {f((64-MARK_H)/2)})'
write('veyr-app-icon.svg', svg(64, 64, f'<rect width="64" height="64" rx="15" fill="{INK}"/><g transform="{ICON_T}">{mark_body(CREAM, EMBER_BRIGHT)}</g>'))
write('veyr-app-icon-mono.svg', svg(64, 64,
    f'<defs><mask id="k"><rect width="64" height="64" fill="#fff"/><g transform="{ICON_T}">{mark_body("#000", "#000")}</g></mask></defs>'
    '<rect width="64" height="64" rx="15" fill="#000" mask="url(#k)"/>'))

ts=f'''// Generated by the brand build (see brand/README.md). Do not edit by hand.
// Mark: {MARK_W} x {MARK_H} grid. Logotype: the mark as "V" + "eyr" in Outfit Bold outlines (SIL OFL 1.1).
export const MARK = {{ width: {MARK_W}, height: {MARK_H}, v: '{V}', block: {{ x: {f(BLOCK["x"])}, y: {BLOCK["y"]}, width: {f(BLOCK["w"])}, height: {BLOCK["h"]}, rx: {BLOCK["rx"]} }} }} as const;
export const LOGOTYPE = {{ width: {LOGO_W}, height: {round(BOTTOM-TOP,3)}, y: {TOP}, textTransform: '{TEXT_T}', text: '{g["d"]}' }} as const;
export const APP_ICON = {{ size: 64, radius: 15, markTransform: '{ICON_T}' }} as const;
export const BRAND = {{ ink: '{INK}', ember: '{EMBER}', emberBright: '{EMBER_BRIGHT}', cream: '{CREAM}' }} as const;
'''
open(os.path.join(ROOT,'src','components','brand','geometry.ts'),'w').write(ts); print('wrote src/components/brand/geometry.ts')
print('V', V, '| logo', LOGO_W, 'x', round(BOTTOM-TOP,3))
